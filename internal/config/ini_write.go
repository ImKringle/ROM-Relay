package config

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// defaultPlatformDirectories mirrors loadV2's built-in remote_search.platforms
// map. WriteINI compares against it so a config that never customized the
// mapping doesn't grow a redundant [remote_search.platforms] section every
// time Settings is saved.
var defaultPlatformDirectories = map[string]string{
	"gb": "gb", "gbc": "gbc", "gba": "gba", "nds": "nds", "3ds": "3ds",
	"nes": "nes", "snes": "snes", "n64": "n64", "genesis": "genesis",
}

// WriteINI regenerates config.ini at dir from c's ini-backed fields, in the
// same section layout as config.example.ini. It is not round-trip
// preserving: comments and formatting a human added by hand are not kept,
// only values, the simpler of the two options the nav/admin design doc left
// open, chosen because ROM Relay's ini dialect has no comment-anchoring
// concept to preserve them against in the first place.
//
// Every field that Load reads from the environment/.env instead of config.ini
// (DatabaseURL, AdminPassword, both access tokens, IGDB credentials, the
// remote-search password) is a field this function never touches, it only
// ever reads the subset of Config that config.ini itself defines, so a secret
// can never end up written to disk here.
func WriteINI(dir string, c Config) error {
	var b strings.Builder
	b.WriteString("# ROM Relay configuration, regenerated by the Settings panel.\n")
	b.WriteString("# Secrets (tokens, passwords, IGDB credentials) live in .env, not here.\n\n")

	section(&b, "library", []kv{
		{"directory", relOrAbs(dir, c.LibraryDirectory)},
		{"database_path", relOrAbs(dir, c.DatabasePath)},
		{"scan_interval_hours", strconv.Itoa(c.LibraryScanIntervalHours)},
		{"metadata_refresh_days", strconv.Itoa(c.MetadataRefreshDays)},
		{"existing_output", c.ExistingOutput},
		{"ui_theme", c.UITheme},
	})
	section(&b, "server", []kv{
		{"listen_address", c.Server.ListenAddress},
		{"port", strconv.Itoa(c.Server.Port)},
		{"advertise_ip", c.Server.AdvertiseIP},
		{"advertise_port", strconv.Itoa(c.Server.AdvertisePort)},
		{"public_base_url", c.Server.PublicBaseURL},
	})
	section(&b, "metadata.libretro", []kv{
		{"enabled", boolStr(c.Metadata.Libretro.Enabled)},
		{"database_directory", relOrAbs(dir, c.Metadata.Libretro.DatabaseDirectory)},
		{"thumbnail_directory", relOrAbs(dir, c.Metadata.Libretro.ThumbnailDirectory)},
		{"auto_update", boolStr(c.Metadata.Libretro.AutoUpdate)},
		{"download_thumbnails", boolStr(c.Metadata.Libretro.DownloadThumbnails)},
	})
	section(&b, "metadata.igdb", []kv{
		{"enabled", boolStr(c.Metadata.IGDB.Enabled)},
	})
	section(&b, "metadata.pokeapi", []kv{
		{"enabled", boolStr(c.Metadata.PokeAPI.Enabled)},
		{"data_directory", relOrAbs(dir, c.Metadata.PokeAPI.DataDirectory)},
	})
	section(&b, "remote_search", []kv{
		{"enabled", boolStr(c.RemoteSearch.Enabled)},
		{"host", c.RemoteSearch.Host},
		{"port", strconv.Itoa(c.RemoteSearch.Port)},
		{"username", c.RemoteSearch.Username},
		{"root_directory", c.RemoteSearch.RootDirectory},
		{"host_key_sha256", c.RemoteSearch.HostKeySHA256},
		{"max_results", strconv.Itoa(c.RemoteSearch.MaxResults)},
		{"max_file_size_mb", strconv.Itoa(c.RemoteSearch.MaxFileSizeMB)},
	})
	if !equalMaps(c.RemoteSearch.PlatformDirectories, defaultPlatformDirectories) {
		var rows []kv
		var platforms []string
		for platform := range c.RemoteSearch.PlatformDirectories {
			platforms = append(platforms, platform)
		}
		sort.Strings(platforms)
		for _, platform := range platforms {
			rows = append(rows, kv{platform, c.RemoteSearch.PlatformDirectories[platform]})
		}
		section(&b, "remote_search.platforms", rows)
	}
	section(&b, "storage", []kv{
		{"save_directory", relOrAbs(dir, c.SaveDirectory)},
	})
	section(&b, "patching", []kv{
		{"enabled", boolStr(c.Patching.Enabled)},
		{"patch_directory", relOrAbs(dir, c.Patching.PatchDirectory)},
		{"output_directory", relOrAbs(dir, c.Patching.OutputDirectory)},
		{"retention_hours", strconv.Itoa(c.Patching.RetentionHours)},
		{"max_rom_size_mb", strconv.Itoa(c.Patching.MaxROMSizeMB)},
		{"max_patch_size_mb", strconv.Itoa(c.Patching.MaxPatchSizeMB)},
		{"timeout_seconds", strconv.Itoa(c.Patching.TimeoutSeconds)},
	})

	tmp, err := os.CreateTemp(dir, "config.ini-*.tmp")
	if err != nil {
		return err
	}
	tmpPath := tmp.Name()
	ok := false
	defer func() {
		_ = tmp.Close()
		if !ok {
			_ = os.Remove(tmpPath)
		}
	}()
	if _, err = tmp.WriteString(b.String()); err != nil {
		return err
	}
	if err = tmp.Sync(); err != nil {
		return err
	}
	if err = tmp.Close(); err != nil {
		return err
	}
	if err = os.Rename(tmpPath, filepath.Join(dir, "config.ini")); err != nil {
		return err
	}
	ok = true
	return nil
}

// BackupINI copies the current config.ini to config.ini.bak, best-effort. A
// missing config.ini (nothing to back up yet) is not an error.
func BackupINI(dir string) error {
	data, err := os.ReadFile(filepath.Join(dir, "config.ini"))
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	return os.WriteFile(filepath.Join(dir, "config.ini.bak"), data, 0644)
}

// RestoreINIBackup replaces config.ini with config.ini.bak, for rolling back
// a save that failed validation. A missing backup means BackupINI ran against
// a directory with no config.ini yet, the correct restore is then to remove
// what WriteINI just wrote, not to leave a file that didn't exist before.
func RestoreINIBackup(dir string) error {
	data, err := os.ReadFile(filepath.Join(dir, "config.ini.bak"))
	if err != nil {
		if os.IsNotExist(err) {
			if rmErr := os.Remove(filepath.Join(dir, "config.ini")); rmErr != nil && !os.IsNotExist(rmErr) {
				return rmErr
			}
			return nil
		}
		return err
	}
	return os.WriteFile(filepath.Join(dir, "config.ini"), data, 0644)
}

type kv struct{ key, value string }

func section(b *strings.Builder, name string, rows []kv) {
	fmt.Fprintf(b, "[%s]\n", name)
	for _, row := range rows {
		fmt.Fprintf(b, "%s = %s\n", row.key, quoteIfNeeded(row.value))
	}
	b.WriteString("\n")
}

// quoteIfNeeded wraps a value in double quotes when it would otherwise be
// ambiguous to parseINI: empty (an absent value and an explicit empty string
// must round-trip as the same thing), or bordered by whitespace.
func quoteIfNeeded(v string) string {
	if v == "" {
		return `""`
	}
	if strings.TrimSpace(v) != v {
		return `"` + v + `"`
	}
	return v
}

func boolStr(v bool) string {
	if v {
		return "true"
	}
	return "false"
}

// relOrAbs writes a path relative to dir when it lives under dir (the common
// case for ROM Relay's own subdirectories), so a freshly regenerated
// config.ini stays as portable as the hand-written example it replaces.
// Anything outside dir is written absolute rather than with a confusing
// string of "..".
func relOrAbs(dir, path string) string {
	rel, err := filepath.Rel(dir, path)
	if err != nil || strings.HasPrefix(rel, "..") {
		return path
	}
	return filepath.ToSlash(rel)
}

func equalMaps(a, b map[string]string) bool {
	if len(a) != len(b) {
		return false
	}
	for k, v := range a {
		if b[k] != v {
			return false
		}
	}
	return true
}
